"""Generate only additional kitchen UI assets; never invokes a firmware build.
Usage: PYTHONDONTWRITEBYTECODE=1 python3 tools/generate_ui_extensions.py --material-font /tmp/kitchen-material-symbols.ttf
Existing generated kitchen_fonts.c and kitchen_symbols.h remain untouched.
"""
import argparse
import hashlib
import io
from pathlib import Path
from PIL import Image, ImageDraw, ImageFont
from generate_timer_fonts import ROOT, ASSETS, asset, inter, lvgl_symbol_source

if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--material-font', type=Path)
    parser.add_argument('--status24-only', action='store_true', help='Generate only kitchen_status_24.c from local Inter')
    parser.add_argument('--large-only', action='store_true', help='Generate only 88px kitchen and large-card control/status subsets')
    parser.add_argument('--overlay-only', action='store_true', help='Generate only bold overlay action labels from local Inter')
    parser.add_argument('--preview', type=Path)
    args = parser.parse_args()
    if sum((args.status24_only, args.large_only, args.overlay_only)) > 1:
        parser.error('Choose only one asset group')
    if args.overlay_only:
        target = ROOT/'components/kitchen_ui/kitchen_overlay_fonts.c'
        target.write_text('/* Generated by tools/generate_ui_extensions.py --overlay-only. Inter SIL OFL 1.1. */\n#include "lvgl.h"\n\n' +
                          asset('kitchen_actions_20', inter(20,700), list(range(32,127)) + [0xb7]) + '\n')
        print(target, target.stat().st_size, 'bytes of C source')
        if args.preview:
            image = Image.new('RGB',(720,180),'#111113'); draw = ImageDraw.Draw(image)
            draw.text((20,12),'Timer name: Kitchen',font=inter(32,700),fill='white')
            draw.text((20,78),'Resume   Cancel timer   Pause   OK',font=inter(20,700),fill='white')
            draw.text((20,122),'Repeat · 23:59:59',font=inter(20,700),fill='white')
            image.save(args.preview)
        raise SystemExit(0)
    if args.status24_only:
        target = ROOT/'components/kitchen_ui/kitchen_status_24.c'
        target.write_text('/* Generated by tools/generate_ui_extensions.py --status24-only. Inter SIL OFL 1.1. */\n#include "lvgl.h"\n\n' +
                          asset('kitchen_status_24', inter(24,700), sorted(set(map(ord,'PAUSED DONE')))) + '\n')
        print(target, target.stat().st_size, 'bytes of C source')
        raise SystemExit(0)
    if args.material_font is None:
        parser.error('--material-font is required unless --status24-only or --overlay-only is selected')
    expected = 'f7837ba8573d9a7a74931618ced8307bc81f96d49af296bf6c8052c772ed5282'
    if hashlib.sha256(args.material_font.read_bytes()).hexdigest() != expected:
        raise SystemExit('Material Symbols input differs from reviewed source')
    codes = {n: int(c, 16) for n, c in (s.split() for s in (ASSETS/'material/codepoints.txt').read_text().splitlines())}
    def material(size):
        font = ImageFont.truetype(str(args.material_font), size)
        values = {'Fill': 0, 'Grade': 0, 'Optical Size': min(size,48), 'Weight': 400}
        font.set_variation_by_axes([values.get(a['name'].decode(), a['default']) for a in font.get_variation_axes()])
        return font
    if args.large_only:
        kitchen = material(88)
        settings = material(52)
        controls = ImageFont.truetype(io.BytesIO(lvgl_symbol_source()),48)
        output = [asset('kitchen_symbols_88', kitchen, sorted(codes[n] for n in ('local_cafe','stockpot','skillet','oven'))),
                  asset('kitchen_settings_52', settings, [0xe8b8]),
                  asset('kitchen_controls_48', controls, [0xf00c,0xf04b,0xf04c]),
                  asset('kitchen_status_36', inter(36,700), sorted(set(map(ord,'PAUSED DONE'))))]
        target = ROOT/'components/kitchen_ui/kitchen_large_assets.c'
        target.write_text('/* Generated by tools/generate_ui_extensions.py --large-only. See FONT_LICENSE.txt. */\n#include "lvgl.h"\n\n'+'\n\n'.join(output)+'\n')
        print(target, target.stat().st_size, 'bytes of C source')
        if args.preview:
            image = Image.new('RGB',(720,390),'#111113'); draw = ImageDraw.Draw(image)
            for row,size in enumerate((40,56,88)):
                draw.text((12,row*125+16),str(size)+' px',font=inter(20,500),fill='white')
                for i,n in enumerate(('local_cafe','stockpot','skillet','oven')):
                    draw.text((120+135*i,row*125+6),chr(codes[n]),font=material(size),fill='white')
            image.save(args.preview)
        raise SystemExit(0)
    medium, settings = material(56), material(36)
    bold18, bold20 = inter(18,700), inter(20,700)
    output = [asset('kitchen_symbols_56', medium, sorted(codes[n] for n in ('local_cafe','stockpot','skillet','oven'))),
              asset('kitchen_settings_36', settings, [0xe8b8]),
              asset('kitchen_status_18', bold18, sorted(set(map(ord,'PAUSED DONE')))),
              asset('kitchen_status_20', bold20, sorted(set(map(ord,'PAUSED DONE'))))]
    target = ROOT/'components/kitchen_ui/kitchen_font_extensions.c'
    target.write_text('/* Generated by tools/generate_ui_extensions.py. Inter OFL / Material Symbols Apache-2.0. */\n#include "lvgl.h"\n\n'+'\n\n'.join(output)+'\n')
    print(target, target.stat().st_size, 'bytes of C source')
    if args.preview:
        image = Image.new('RGB',(680,180),'#111113'); draw = ImageDraw.Draw(image)
        for i,n in enumerate(('local_cafe','stockpot','skillet','oven')):
            draw.text((20+105*i,12),chr(codes[n]),font=medium,fill='white')
        draw.text((470,20),chr(0xe8b8),font=settings,fill='white')
        draw.text((20,110),'PAUSED   DONE',font=bold20,fill='white')
        draw.text((300,110),'PAUSED   DONE',font=bold18,fill='white')
        image.save(args.preview)
